"""Writes a README.md in every jurisdiction folder: the folder's front page on GitHub.

    python tools/folder_readmes.py            write
    python tools/folder_readmes.py --check    exit 1 if any README would change

Each page names every repository under its folder, grouped by kind (legislation of the whole country, of each
subdivision, regulations and guidance, case law by court), with what the corpus says it covers, the kind of history it
holds, how far its record runs, the freshness monitor's status and a link to the repository's current main. Where
data/completeness.json has an independent check of the country, the page opens with it. Standard library only; reads
manifest.json, data/freshness.tsv, data/completeness.json and each folder's jurisdiction.json. tools/describe.py
runs it after rewriting those files, so the pages follow every move of the pins.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEVELS_WHOLE = ('national', 'federal', 'bund', 'union', 'uk')
LEGISLATION = ('acts', 'statutes', 'legislation', 'instruments', 'usc', 'code')
REGULATION = ('cfr', 'regulations', 'irs-guidance', 'guidance', 'sublaws')
MARK = '<!-- generated by tools/folder_readmes.py: edits here are overwritten -->'


def kind_of(path: str) -> str:
    leaf = path.rsplit('/', 1)[-1]
    if leaf == 'caselaw' or leaf.endswith('caselaw'):
        return 'case law'
    if leaf in REGULATION:
        return 'regulations and guidance'
    if leaf in LEGISLATION:
        whole = path.count('/') >= 2 and path.split('/')[1] in LEVELS_WHOLE
        return 'legislation, whole country' if whole else 'legislation, subdivisions'
    return 'other records'


ORDER = ['legislation, whole country', 'legislation, subdivisions', 'regulations and guidance', 'case law', 'other records']


def cell(s) -> str:
    return str(s if s not in (None, '') else '\u2013').replace('|', '\\|').replace('\n', ' ').strip()


def repo_url(corpus: dict) -> str:
    url = str(corpus.get('url') or corpus.get('repo') or '').strip()
    return url[:-4] if url.endswith('.git') else url


def pct(v) -> str:
    if v is None:
        return '\u2013'
    v = float(v)
    return f'{v:.1f}%' if 0 < v < 10 and v % 1 else f'{v:.0f}%'


def load_tsv(p: Path) -> dict[str, dict]:
    if not p.exists():
        return {}
    lines = p.read_text(encoding='utf-8').splitlines()
    hdr = lines[0].split('\t') if lines else []
    return {l.split('\t')[0]: dict(zip(hdr, l.split('\t'))) for l in lines[1:] if l.strip()}


def federation_block(name: str, c: dict) -> list[str]:
    """A federation's whole-country estimate: headline shares, then each federal body of law and each state."""
    link = '[data/completeness.json](' + '../' * name.count('/') + '../data/completeness.json)'
    chart = c.get('chart')
    out = [f'## Completeness of the whole country, checked {c.get("verified_on", "")}', '']
    if chart and (ROOT / name / f'{chart}-light.svg').exists():
        out += ['<picture>', f'<source media="(prefers-color-scheme: dark)" srcset="{chart}-dark.svg">',
                f'<img alt="How complete global-law is for the whole country: federal law, each state and territory code, '
                f'case law and local law" src="{chart}-light.svg" width="880">', '</picture>', '']
    out += ['| ' + ' | '.join(h[0] for h in c['headline']) + ' |', '| ' + ' | '.join('---' for _ in c['headline']) + ' |',
            '| ' + ' | '.join(f'{h[1]:g}%' if chart else f'{pct(h[1])} ({h[2]} confidence)' for h in c['headline']) + ' |', '',
            cell(c.get('verdict', '')), '',
           f'{cell(c.get("method", ""))} Every figure is in {link}.', '',
           ] + plan_block(c.get('plan')) + [
           '<details><summary>Federal law, part by part</summary>', '',
           '| Part | Held | Confidence | Basis |', '| --- | --- | --- | --- |']
    out += [f'| {cell(f["part"])} | {f["share"]:g}% | {f["confidence"]} | {cell(f["basis"])} |' for f in c.get('federal', [])]
    states = c.get('states', [])
    out += ['', '</details>', '', f'<details><summary>The {len(states)} states, territories and D.C., one by one</summary>', '',
            '| Jurisdiction | Code held | Basis | Constitution | Case law (of CAP) |', '| --- | --- | --- | --- | --- |']
    out += [f'| {cell(s["name"])} | {s["share"]:g}% | {cell(s["basis"])} | '
            f'{"held" if s.get("constitution") else "not held"} | {(format(min(100.0, s["case_law"]), "g") + "%") if s.get("case_law") is not None else chr(0x2013)} |'
            for s in states]
    return out + ['', '</details>', '']


def plan_block(plan: dict | None) -> list[str]:
    """The plan for every source a lawyer or citizen needs, part by part (as romania-law's PLAN.md)."""
    if not plan:
        return []
    out = [f'### The plan: every source a lawyer or citizen needs', '',
           f'**{plan["pct"]:g}%** of the plan is in global-law, weighted by how binding each source is and how often it is '
           f'used; **{plan["collected_pct"]:g}%** counting sources collected but not yet in global-law. '
           f'{plan["low_confidence_weight"]:g}% of the weight is in parts whose official total is an estimate. Updated {plan["updated"]}.', '',
           '| Part | Will be in | Weight | Progress | How | Status |', '| --- | --- | ---: | --- | --- | --- |']
    groups = []
    for p in plan['parts']:
        if p['group'] not in groups:
            groups.append(p['group'])
    for g in groups:
        gp = next((x for x in plan.get('groups', []) if x['group'] == g), None)
        out.append(f'| **{g}** | | **{gp["weight"]:g}%** | **{gp["pct"]:g}%** | | |' if gp else f'| **{g}** | | | | | |')
        for p in (p for p in plan['parts'] if p['group'] == g):
            pc = f'{p["pct"]:g}%' + (f' ({p["collected_pct"]:g}% collected)' if p.get('collected_pct') is not None else '')
            est = '' if p['confidence'] == 'high' else f'; {p["confidence"]}-confidence total'
            out.append(f'| {cell(p["part"])} | `{cell(p["where"])}` | {p["weight"]:g}% | {cell(p["progress"])} · {pc} | {cell(p["how"])}{est} | {p["status"]} |')
    return out + ['', "Totals are the publishers' own counts where they exist (eCFR, the Federal Register API, CAP, the Census of "
                  'Governments, the BIA list), otherwise the best public estimate, marked.', '']


def completeness_block(name: str, c: dict) -> list[str]:
    if c.get('kind') == 'federation':
        return federation_block(name, c)
    s, est = c.get('scores', {}), c.get('estimates', {})

    def shown(metric, value):
        e = est.get(metric)
        if value is None:
            return '\u2013'
        if e:
            r = e.get('range')
            rng = f', {r[0]}\u2013{r[1]}%' if isinstance(r, list) and len(r) == 2 else ''
            return f'{pct(value)} (estimate, {e.get("confidence", "")} confidence{rng})'
        return pct(value)
    regions = 'not applicable' if c.get('regions_not_applicable') else shown('subnational_pct', s.get('subnational_pct'))
    return [
        f'## Completeness, checked against the official sources ({c.get("verified_on", "")})',
        '',
        '| Constitution | Main codes | National law | Law-making regions | Case law |',
        '| --- | --- | --- | --- | --- |',
        f'| {"held" if s.get("constitution") else "not held"} | {shown("codes_pct", s.get("codes_pct"))} | '
        f'{shown("national_primary_pct", s.get("national_primary_pct"))} | {regions} | {shown("case_law_pct", s.get("case_law_pct"))} |',
        '',
        f'{cell(c.get("verdict", ""))}',
        '',
        'Shares are of what exists, not of what each repository says it holds; estimates are marked, with their method in '
        '[data/completeness.json](' + '../' * name.count('/') + '../data/completeness.json).',
        '',
    ]


def page(folder: str, body: dict, corpora: dict[str, dict], fresh: dict, complete: dict, names: dict) -> str:
    depth = folder.count('/')
    up = '../' * (depth + 1)
    crumbs = [f'[global-law]({up})']
    parts = folder.split('/')
    for i in range(len(parts) - 1):
        sub = '/'.join(parts[:i + 1])
        crumbs.append(f'[{names.get(sub, parts[i])}]({"../" * (len(parts) - 1 - i)})')
    name = body.get('name') or parts[-1].replace('-', ' ').title()
    mine = sorted(p for p in corpora if p.startswith(folder + '/'))
    groups: dict[str, list[str]] = {}
    for p in mine:
        groups.setdefault(kind_of(p), []).append(p)
    counts = ', '.join(f'{len(groups[k])} {k}' for k in ORDER if groups.get(k))
    out = [MARK, f'# {name}', '', ' / '.join(crumbs + [name]), '']
    if mine:
        out += [f'{len(mine)} {"repository" if len(mine) == 1 else "repositories"} under this folder ({counts}). Each row links to the '
                'repository\'s current `main`; the folder of the same path is the submodule global-law pins and reads. '
                '"Coverage" is what the corpus says of itself; freshness is global-law\'s monitor.', '']
    else:
        out += ['No repository under this folder yet: see SOURCES.md for the official sources and why nothing is built.', '']
    if depth == 0 and folder in complete:
        out += completeness_block(folder, complete[folder])
    for k in ORDER:
        rows = groups.get(k)
        if not rows:
            continue
        out += [f'## {k[0].upper() + k[1:]} ({len(rows)})', '',
                '| Corpus | Repository | Coverage | History | Record to | Freshness |', '| --- | --- | --- | --- | --- | --- |']
        for p in rows:
            c = corpora[p]
            url = repo_url(c)
            rname = url.rsplit('/', 1)[-1] if url else ''
            rel = p[len(folder) + 1:]
            f = fresh.get(p, {})
            out.append(f'| `{cell(rel)}` | {f"[{rname}]({url}/tree/main)" if url else chr(0x2013)} | {cell(c.get("coverage") or c.get("name"))} | '
                       f'{cell(c.get("history"))} | {cell(c.get("record_to"))} | {cell(f.get("status"))} |')
        out.append('')
    subs = [j for j in body.get('jurisdictions', []) if j.rsplit('/', 1)[0] == folder]
    if subs:
        out += ['## Jurisdictions in this folder', '']
        for j in sorted(subs):
            n = sum(1 for p in corpora if p.startswith(j + '/'))
            out.append(f'- [{names.get(j, j.rsplit("/", 1)[-1])}]({j.rsplit("/", 1)[-1]}/) ({n} {"repository" if n == 1 else "repositories"})')
        out.append('')
    return '\n'.join(out).rstrip() + '\n'


PAGE = 'https://github.com/lexifina/global-law/tree/main/'


def link_fields(folder: str, body: dict, corpora: dict[str, dict]) -> dict:
    """The folder's front page and every repository under it, added to its jurisdiction.json ("repo" is kept: the
    country's main legislation repository, as before)."""
    body['page'] = PAGE + folder
    body['repos'] = [{'path': p, 'kind': kind_of(p), 'repo': repo_url(corpora[p])}
                     for p in sorted(corpora) if p.startswith(folder + '/') and repo_url(corpora[p])]
    return body


def build() -> dict[str, str]:
    manifest = json.loads((ROOT / 'manifest.json').read_text(encoding='utf-8'))
    corpora = {c['path']: c for c in manifest.get('corpora', [])}
    fresh = load_tsv(ROOT / 'data' / 'freshness.tsv')
    cp = ROOT / 'data' / 'completeness.json'
    complete = json.loads(cp.read_text(encoding='utf-8')).get('jurisdictions', {}) if cp.exists() else {}
    bodies = {}
    for jf in ROOT.glob('**/jurisdiction.json'):
        rel = jf.parent.relative_to(ROOT).as_posix()
        if rel in ('.', '') or rel.startswith(('.git', 'tools', 'data')):
            continue
        try:
            bodies[rel] = json.loads(jf.read_text(encoding='utf-8'))
        except ValueError:
            continue
    names = {f: b.get('name') or f.rsplit('/', 1)[-1] for f, b in bodies.items()}
    pages = {}
    for folder, body in bodies.items():
        # only folders that hold a corpus, or a folder that does (a country with nothing yet keeps SOURCES.md)
        if any(p.startswith(folder + '/') for p in corpora) or folder.count('/') == 0:
            pages[f'{folder}/README.md'] = page(folder, body, corpora, fresh, complete, names)
        new = json.dumps(link_fields(folder, dict(body), corpora), ensure_ascii=False, indent=2) + '\n'
        pages[f'{folder}/jurisdiction.json'] = new
    return pages


def write(check: bool = False) -> list[str]:
    changed = []
    for name, text in build().items():
        p = ROOT / name
        current = p.read_text(encoding='utf-8').replace('\r\n', '\n') if p.exists() else None
        if current is not None and name.endswith('README.md') and MARK not in current:
            continue  # a README someone wrote by hand is left alone
        if current != text:
            changed.append(name)
            if not check:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_bytes(text.encode('utf-8'))
    return changed


if __name__ == '__main__':
    check = '--check' in sys.argv
    changed = write(check)
    print(f"{len(changed)} folder page(s) and jurisdiction.json file(s) {'would change' if check else 'written'}")
    sys.exit(1 if check and changed else 0)
