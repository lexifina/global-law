"""Write LegalProofs/USTax/Family/Found.lean: the search's results as kernel-checked statements.

    python tools/taxcode/loopholes/family_found.py [entries.json Module]

(default: family_found.json → Found.lean; family_cliff.json Cliff → Cliff.lean holds the support-test cliff)

Each entry is a family, a list of moves (as in family_search.py) and a sentence. The figures are computed by the Lean
runner first, then written as `theorem … : (simulate spec plan).wealth = N := by decide`, so the kernel re-derives
every one from the rules.
"""
import json
from family_lib import FAMILIES, ROOT, run
from family_search import build, specs

import sys
SRC = sys.argv[1] if len(sys.argv) > 2 else "family_found.json"
MOD = sys.argv[2] if len(sys.argv) > 2 else "Found"
ENTRIES = json.load(open(ROOT / "tools" / "taxcode" / "loopholes" / SRC, encoding="utf-8"))


def lean_int(x):
    return f"({x})" if x < 0 else str(x)


def lean_list(xs, f=str):
    return "[" + ", ".join(f(x) for x in xs) + "]"


def lean_spec(name, s):
    def par(p):
        return (f"{{ age := {p['age']}, wage := {p['wage']}, ira := {p['ira']}, roth := {p['roth']}, ss := {p['ss']}, "
                f"ssAge := {p['ssAge']}, rmdAge := {p['rmdAge']}, retireAge := {p['retireAge']} }}")
    kids = lean_list(s["kids"], lambda k: f"{{ age := {k['age']}, studentThrough := {k['studentThrough']}, "
                     f"adultWage := {k['adultWage']}, support := {k['support']} }}")
    caps = lean_list(s["kidWageCap"], lambda c: f"({c[0]}, {c[1]})")
    b = s["brokerage"]
    return (f"def {name} : Spec :=\n  {{ head := {par(s['head'])},\n    spouse := {par(s['spouse'])},\n"
            f"    brokerage := ⟨{b['value']}, {b['basis']}⟩, business := {s['business']}, spending := {s['spending']},\n"
            f"    charity := {s['charity']}, mortgage := {s['mortgage']}, salt := {s['salt']}, kids := {kids},\n"
            f"    growthBp := {s['growthBp']}, divBp := {s['divBp']}, intBp := {s['intBp']}, premium := {s['premium']},\n"
            f"    horizon := {s['horizon']}, gainsInDni := {'true' if s['gainsInDni'] else 'false'}, kidWageCap := {caps} }}\n")


DEFAULT = dict(convH=0, convS=0, convTo=0, harvestTo=0, gifts=[], trustFund=0, trustDistBp=[], trustHarvestTo=0,
               kidWage=[], kidRoth=[], kidHarvestTo=[], form8814=[], charity=-1, charityShares=False, mfs=False)


def lean_year(p):
    parts = []
    for k, d in DEFAULT.items():
        v = p[k]
        if v == d or (isinstance(v, list) and not any(v)): continue
        if isinstance(v, bool): parts.append(f"{k} := {'true' if v else 'false'}")
        elif isinstance(v, list):
            parts.append(f"{k} := " + lean_list(v, lambda x: ('true' if x else 'false') if isinstance(x, bool) else lean_int(x)))
        else: parts.append(f"{k} := {lean_int(v)}")
    return "{ " + ", ".join(parts) + " }" if parts else "{}"


def main():
    sp = specs()
    jobs, used = [], {}
    for e in ENTRIES:
        name, plan = build(e["family"], [tuple(m) for m in e["moves"]])
        jobs.append((name, plan, False)); used[name] = sp[name]
    outs = run(sp, jobs, procs=8, tag=MOD.lower())
    L = ["import LegalProofs.USTax.Family.Driver", "",
         "/-!", "# What the family search found, re-checked by the kernel", "",
         "Each figure is the after-tax family wealth at the parents' death (real 2025 dollars, 2025 law in every year;",
         "see `Driver.lean`) for one family and one plan. The search (`tools/taxcode/loopholes/family_search.py`) ran the",
         "plans through the compiled runner; here `decide` makes the kernel recompute each one from the rules.",
         "Generated by `tools/taxcode/loopholes/family_found.py` from `family_found.json`.", "-/", "",
         "set_option maxRecDepth 200000", "set_option maxHeartbeats 0", "", f"namespace Legal.USTax.Family.{MOD}", "open Legal.USTax.Family", ""]
    for name, s in used.items():
        L.append(lean_spec(name.replace("+dni", "Dni"), s))
    for e, (name, plan, _), o in zip(ENTRIES, jobs, outs):
        pn = f"plan_{e['id']}"
        L.append(f"def {pn} : List YearPlan := [\n  " + ",\n  ".join(lean_year(p) for p in plan) + "]\n")
        L.append(f"/-- {e['text']} -/")
        L.append(f"theorem {e['id']} : (simulate {name.replace('+dni', 'Dni')} {pn}).wealth = {o['wealth']} := by decide\n")
        e["wealth"] = o["wealth"]
    L.append(f"end Legal.USTax.Family.{MOD}")
    (ROOT / "LegalProofs" / "USTax" / "Family" / f"{MOD}.lean").write_text("\n".join(L) + "\n", encoding="utf-8")
    for e in ENTRIES: print(e["id"], e["wealth"])


if __name__ == "__main__":
    main()
