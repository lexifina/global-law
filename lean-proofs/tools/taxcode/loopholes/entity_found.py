"""Write LegalProofs/USTax/Entity/Found.lean: the search's chosen plans as kernel-checked theorems.

    python tools/taxcode/loopholes/entity_found.py

Reads DATA/found.json: [{"label", "scenario", "plan", "wealth"}] (written by entity_report.py) and emits one
`theorem <label> : (simulate <scenario> <plan>).wealth = <wealth> := by decide` per entry, so the kernel recomputes
each figure from the rules.
"""
import json
from entity_lib import ROOT, DATA, SCENARIOS

def b(x): return "true" if x else "false"

def spec_lean(name, s):
    z = s["biz"]
    kids = ", ".join(f"⟨{k['age']}, {k['wage']}⟩" for k in s["kids"])
    return f"""def {name} : ESpec :=
  {{ ageH := {s['ageH']}, ageS := {s['ageS']}, wageS := {s['wageS']}, spending := {s['spending']},
    brokerage := ⟨{s['brokerage']['value']}, {s['brokerage']['basis']}⟩,
    biz := {{ profit := {z['profit']}, growthBp := {z['growthBp']}, fastYears := {z['fastYears']}, fastBp := {z['fastBp']},
             multipleX10 := {z['multipleX10']}, staffWages := {z['staffWages']}, ubia := {z['ubia']},
             assetBasis := {z['assetBasis']}, sstb := {b(z['sstb'])}, rcLo := {z['rcLo']}, rcHi := {z['rcHi']},
             reasonableNeeds := {z['reasonableNeeds']}, capitalMaterial := {b(z['capitalMaterial'])},
             needBp := {z['needBp']}, needYears := {z['needYears']} }},
    kids := [{kids}], growthBp := {s['growthBp']}, divBp := {s['divBp']}, intBp := {s['intBp']},
    horizon := {s['horizon']} }}
"""

def plan_lean(p):
    forms = ", ".join(f"({y}, .{f})" for y, f in p["forms"])
    gifts = ", ".join(f"⟨{g['year']}, {g['bp']}, {b(g['toTrusts'])}⟩" for g in p["gifts"])
    return (f"{{ forms := [{forms}], salary := {p['salary']}, payoutBp := {p['payoutBp']}, gifts := [{gifts}], "
            f"exit := .{p['exit']} }}")

def main():
    found = json.load(open(DATA / "found.json"))
    used = sorted({f["scenario"] for f in found})
    out = ['import LegalProofs.USTax.Entity.Driver', '', '/-!', '# What the entity search found, re-checked by the kernel', '',
           'Each figure is the after-tax family wealth at the parents\' death (real 2025 dollars, 2025 law in every year; see',
           '`Driver.lean`) for one scenario and one plan. The search ran the plans through `Run.lean`; here `decide` makes the',
           'kernel recompute each one from the rules. Generated by `tools/taxcode/loopholes/entity_found.py`.', '-/', '',
           'set_option maxRecDepth 400000', 'set_option maxHeartbeats 0', '',
           'namespace Legal.USTax.Entity.Found', 'open Legal.USTax.Entity', '']
    for n in used:
        out.append(spec_lean(n, SCENARIOS[n]))
    for f in found:
        out.append(f"/-- {f['note']} -/" if f.get("note") else "")
        out.append(f"def plan_{f['label']} : EPlan := {plan_lean(f['plan'])}")
        out.append(f"theorem {f['label']} : (simulate {f['scenario']} plan_{f['label']}).wealth = {f['wealth']} := by decide")
        out.append("")
    out.append("end Legal.USTax.Entity.Found")
    (ROOT / "LegalProofs/USTax/Entity/Found.lean").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(len(found), "theorems")

if __name__ == "__main__":
    main()
