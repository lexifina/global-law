def ifchain_table(name, rows):
    """annual Percentage Method table -> Nat function of annual wage (dollars) giving cents"""
    body = []
    for i in range(len(rows) - 1, -1, -1):
        A, C, Dp = rows[i]
        expr = f'{C} + {Dp} * (w - {A})'
        body.append((A, expr))
    s = 'fun w => '
    # rows ascending; build: if w < A1 then e0 else if w < A2 then e1 ...
    rows_s = sorted(rows)
    parts = []
    for i, (A, C, Dp) in enumerate(rows_s):
        e = f'{C} + {Dp} * (w - {A})' if (C or Dp) else '0'
        if i + 1 < len(rows_s):
            parts.append(f'if w < {rows_s[i + 1][0]} then {e} else')
        else:
            parts.append(e)
    return f'def {name} (w : Nat) : Nat :=\n  ' + '\n  '.join(parts) + '\n'

def ifchain_tax(name, tops, col):
    parts = []
    lows = [0] + tops
    cs = [0] + col
    for i in range(len(lows)):
        e = f'{cs[i]} + {RATES[i]} * (x - {lows[i]})' if i else f'10 * x'
        parts.append(f'if x ≤ {lows[i + 1]} then {e} else' if i + 1 < len(lows) else e)
    return f'def {name} (x : Nat) : Nat :=\n  ' + '\n  '.join(parts) + '\n'

