"""Generate TaxCode/Indexing/CPI.lean (index data) and one Lean file per Rev. Proc. from spec.ITEMS / derived.DERIVED.

    python3 -I tools/arith/gen_lean.py
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cpi import vintage, bls, med_vintage, VINTAGE, MED_VINTAGE, march_vintage, MARCH_VINTAGE
import index
from spec import ITEMS
import spec_old  # noqa: F401
from derived import DERIVED

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'TaxCode', 'Indexing')

def series_lean(name, data, lo, doc):
    rows = sorted(k for k in data if k >= lo)
    body = ',\n  '.join(', '.join(f'({y}, {m}, {data[(y, m)]})' for (y, m) in rows[i:i + 6]) for i in range(0, len(rows), 6))
    return f'/-- {doc} -/\ndef {name} : Series := [\n  {body}]\n'

def gen_cpi():
    out = ['/- Generated by tools/arith/gen_lean.py from ~/docs/data/cpi (do not edit). Values in thousandths. -/',
           'import TaxCode.Indexing.Formula', 'namespace TaxCode.Indexing', '']
    for y, d in VINTAGE.items():
        out.append(series_lean(f'ccpiu_v{y}', vintage(y), (2015, 9),
            f'C-CPI-U (BLS SUUR0000SA0) as of {d} (ALFRED vintage; release of the August {y} index); Sep 2015 on.'))
    for y, d in MARCH_VINTAGE.items():
        out.append(series_lean(f'ccpiu_mar_v{y}', march_vintage(y), (2015, 4),
            f'C-CPI-U as of {d} (ALFRED vintage; release of the March {y} index), for §223(g); Apr 2015 on.'))
    out.append(series_lean('ccpiu_latest', bls('SUUR0000SA0'), (2015, 4),
            'C-CPI-U, latest values (BLS public API v2, retrieved 2026-11-16).'))
    out.append(series_lean('cpiu', bls('CUUR0000SA0'), (1984, 4),
            'CPI-U, U.S. city average, all items, not seasonally adjusted (BLS CUUR0000SA0; never revised).'))
    for y, d in MED_VINTAGE.items():
        mv = med_vintage(y)
        out.append(series_lean(f'ccpiu_med_v{y}', {k: v for k, v in mv.items() if k[1] == 8}, (2015, 8),
            f'Medical care component of the C-CPI-U (SUUR0000SAM), August values, as of {d} (ALFRED).'))
    pm = bls('CUUR0000SAM')
    out.append(series_lean('cpiu_med', {k: v for k, v in pm.items() if k == (1996, 8) or k[0] >= 2016 and k[1] == 8}, (1996, 8),
            'Medical care component of the CPI-U (CUUR0000SAM), August values used (BLS).'))
    out.append('end TaxCode.Indexing\n')
    open(os.path.join(OUT, 'CPI.lean'), 'w', newline='\n').write('\n'.join(out))

def lname(doc): return 'RP' + doc[3:].replace('-', '_')

def rnd_lean(r):
    k = r[0]
    return {'inc_down': lambda: f'.incDown {r[1]}', 'inc_near': lambda: f'.incNear {r[1]}', 'amt_down': lambda: f'.amtDown {r[1]}',
            'amt_near': lambda: f'.amtNear {r[1]}', 'pen': lambda: f'.pen {r[1]} {r[2]} {r[3]}', 'none': lambda: '.none'}[k]()

def base_lean(by): return '.medical' if by == 'med' else f'(.year {by})'

def series_for(cy, final=False):
    C = 'ccpiu_latest' if final else f'ccpiu_v{cy - 1}'
    M = f'ccpiu_med_v{cy - 1}' if (cy - 1) in MED_VINTAGE else 'ccpiu_latest'
    return f'{C} cpiu {M} cpiu_med'

def comp_expr(it, cy=None, final=False):
    cy = cy or it['cy']
    if it['rnd'][0] == 'fixed': return str(it['base'])
    if isinstance(it['base'], list):
        parts = '[' + ', '.join(f'({b}, {y})' for b, y in it['base']) + ']'
        return f'adjustSumNear {series_for(cy, final)} {parts} {cy} {it["rnd"][1]}'
    return f'adjust {series_for(cy, final)} {it["base"]} {base_lean(it["by"])} {cy} ({rnd_lean(it["rnd"])})'

def money(v, unit):
    if unit == 'c': return f'${v // 100}.{v % 100:02d}'
    if unit == 'm': return f'{v / 10:.1f} cents'
    return f'${v:,}'

def gen_doc(doc, results, derived):
    ns = lname(doc)
    out = [f'/- Generated by tools/arith/gen_lean.py (do not edit): Rev. Proc. {doc[3:]} recomputed from the statute. -/',
           'import TaxCode.Indexing.CPI', f'namespace TaxCode.Indexing.{ns}', 'open TaxCode.Indexing', '']
    for r in results:
        if r['doc'] != doc: continue
        n = r['id']
        hdr = (f"/-- Rev. Proc. {doc[3:]} §{r['sec']}: {r['cite']}. Base {r['base']} "
               f"{'(base year ' + str(r['by']) + ')' if r['by'] not in (None, 'parts') else ''}; COLA for {r['cy']}; "
               f"rounding {r['rnd']}. {r['note']} -/")
        out.append(hdr.replace('  ', ' '))
        out.append(f"def {n} : Nat := {comp_expr(r) if r['comp'] is not None else '0'}")
        if r['pub'] is not None:
            out.append(f"def pub_{n} : Nat := {r['pub']}")
        st = r['status']
        if r['comp'] is None:
            # statutory COLA needs a month that was never published
            out.append(f"/-- the statutory index average for {r['cy'] - 1} is not computable: a month is missing -/")
            out.append(f"theorem {n}_incomplete : complete ccpiu_v{r['cy'] - 1} {r['cy'] - 1} = false := by decide")
        elif r['pub'] is None:
            out.append(f"theorem {n}_value : {n} = {r['comp']} := by decide")
        elif st == 'match':
            out.append(f"theorem {n}_matches : {n} = pub_{n} := by decide")
        elif st == 'rounding':
            # no statutory rounding: published figure within one rounding unit of the exact amount
            out.append(f"theorem {n}_value : {n} = {r['comp']} := by decide")
        else:
            d = r['pub'] - r['comp']
            rel = f"pub_{n} = {n} + {d}" if d > 0 else f"pub_{n} + {-d} = {n}"
            out.append(f"theorem {n}_differs : {n} = {r['comp']} ∧ {rel} := by decide")
        if r.get('alt'):
            a = r['alt']
            out.append(f"/-- {a['why']} -/")
            out.append(f"def {n}_{a['tag']} : Nat := {a['expr']}")
            out.append(f"theorem {n}_{a['tag']}_value : {n}_{a['tag']} = {a['val']} := by decide")
        out.append('')
    for d in derived:
        if d['doc'] != doc: continue
        out.append(f"/-- {d['desc']} -/")
        out.append(f"theorem {d['id']} : {d['lean']} := by decide")
        out.append('')
    out.append(f'end TaxCode.Indexing.{ns}\n')
    open(os.path.join(OUT, f'{ns}.lean'), 'w', newline='\n').write('\n'.join(out))
    return ns

if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    gen_cpi()
    results = json.load(open(os.path.join(HERE, 'out', 'index.json')))
    docs = sorted({r['doc'] for r in results})
    names = [gen_doc(d, results, DERIVED) for d in docs]
    print('generated', names)
