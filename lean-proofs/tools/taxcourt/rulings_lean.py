"""Generate LegalProofs/USTax/TaxCourt/Rulings.lean: every encoded Tax Court case as a Lean value, with one `#guard`
per holding that Lean reproduces.

    python tools/taxcourt/rulings_lean.py <taxcourt dir>

Runs the batch runner over every <id>.case.json, keeps the checks that came out equal to the opinion, and writes a Lean
file in which each such check is re-evaluated by Lean when the file is elaborated:

    #guard holds tcsumm_2024_10 "earlyDistributionTax"

so `lake env lean LegalProofs/USTax/TaxCourt/Rulings.lean` succeeding means every listed holding is recomputed from the
court's findings. Holdings that differ, depend on judgment, or are outside the model are listed in comments.
"""
import glob, json, subprocess, sys, tempfile, os
from pathlib import Path

D = Path(sys.argv[1]) / "encoded"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "LegalProofs" / "USTax" / "TaxCourt" / "Rulings.lean"


def load(p):
    raw = Path(p).read_bytes()
    for enc in ("utf-8", "utf-8-sig", "cp1252"):
        try:
            return json.loads(raw.decode(enc))
        except (UnicodeDecodeError, json.JSONDecodeError):
            pass
    raise ValueError(p)


entries = []
for p in sorted(glob.glob(str(D / "*.case.json"))):
    cid = Path(p).name.split(".")[0]
    d = load(p)
    for k, c in enumerate(d if isinstance(d, list) else [d]):
        entries.append((f"{cid}" + (f"_{k}" if isinstance(d, list) and len(d) > 1 else ""), c))

tmp = Path(tempfile.mkdtemp())
outs = []
for name, c in entries:
    (tmp / "in.json").write_text(json.dumps(c), encoding="utf-8")
    r = subprocess.run(["lake", "env", "lean", "--run", "LegalProofs/USTax/TaxCourt/Run.lean", str(tmp / "in.json"),
                        str(tmp / "out.json")], cwd=ROOT, capture_output=True, text=True)
    if r.returncode == 2 or not (tmp / "out.json").exists():
        outs.append({"citation": name, "error": (r.stderr or r.stdout).strip()[:200]})
    else:
        outs.append(json.loads((tmp / "out.json").read_text(encoding="utf-8"))[0])
        (tmp / "out.json").unlink()

lines = ["import LegalProofs.USTax.TaxCourt", "",
         "/-! # Tax Court rulings recomputed in Lean (generated by tools/taxcourt/rulings_lean.py; do not edit)",
         "",
         "Each case is the JSON encoding of the court's findings of fact. Each `#guard` re-runs `decideCase` on it and",
         "checks one holding against the figure or answer the opinion states. -/", "",
         "namespace Legal.USTax.TaxCourt.Rulings", "open Legal.USTax.TaxCourt", "",
         "def holds (s : String) (item : String) : Bool :=",
         "  match parseCase s with",
         "  | .ok c => ((decideCase c).checks.find? (·.item == item)).map (·.ok) |>.getD false",
         "  | .error _ => false", ""]
n = 0
for (name, c), o in zip(entries, outs):
    ident = name.replace("-", "_")
    js = json.dumps(c, ensure_ascii=False).replace("\\", "\\\\").replace('"', '\\"')
    if "error" in o:
        lines.append(f"-- {name}: not parsed: {o['error']}")
        lines.append("")
        continue
    lines.append(f"/-- {o.get('citation', name)} (tax year {o.get('taxYear')}). -/")
    lines.append(f'def {ident} : String := "{js}"')
    for ch in o.get("checks", []):
        item = ch["item"].replace('"', '\\"')
        if ch.get("ok"):
            lines.append(f'#guard holds {ident} "{item}"')
            n += 1
        else:
            lines.append(f"-- differs: {ch['item']}: opinion {ch.get('expected')}, Lean {ch.get('computed')}")
    lines.append("")
lines += ["end Legal.USTax.TaxCourt.Rulings", ""]
OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"wrote {OUT} with {len(entries)} case entries and {n} guarded holdings")
