"""Build conformity.json / conformity.md (tax year 2025, 50 states + DC).
Columns and where each comes from:
  start        starting point of the state base. 'verified' only where an official page was read (cited);
               otherwise 'unverified' = from general knowledge, not checked in this run.
  sch1a_pe     does the state tax fall with the federal Schedule 1-A deductions (tips 20k, overtime 10k, car interest
               8k)? Measured with PolicyEngine-US 2.138.1 (probe_2025.json): a model observation, not law.
  hsa_pe       state tax falls with a 4,000 HSA deduction (PE).
  fedtax_ded   state deduction for federal income tax (Ala. Code 40-18-15; RSMo 143.171; ORS 316.800; repeals: LA
               Acts 2021 No. 39 from 2022, MT SB 399 from 2024 - PE parameter files and their citations).
  eitc_pct / cdcc_pct  share of the federal credit, PE parameter value in force for 2025 (PE cites the source).
  itemize_tie  'tied (PE run)' where the blind search found the state follows the federal itemizing choice;
               otherwise 'not checked'.
Unknowns are marked, not guessed."""
import json
probe = json.load(open("probe_2025.json"))
cm = json.load(open("credit_matches_pe.json"))
NO_TAX = {"AK", "FL", "NV", "NH", "SD", "TN", "TX", "WA", "WY"}
START = {  # (starting point, confidence, source)
    "IA": ("federal taxable income (from 2023), rolling conformity", "verified",
           "https://revenue.iowa.gov/taxes/tax-guidance/individual-income-tax/1040-expanded-instructions/conformity-irc"),
    "CO": ("federal taxable income", "unverified", ""), "ND": ("federal taxable income", "unverified", ""),
    "SC": ("federal taxable income; OBBBA Schedule 1-A amounts added back (PE sc_obbba_addback)", "unverified", ""),
    "MT": ("federal taxable income (from 2024, SB 399)", "unverified", "PE parameter citation"),
    "ID": ("federal AGI; Schedule 1-A deductions adopted by Idaho's 2026 conformity law (PE citation: tax.idaho.gov press release)", "unverified", ""),
    "PA": ("own classes of income", "unverified", ""), "NJ": ("own gross income", "unverified", ""),
    "MA": ("own (Part A/B/C)", "unverified", ""), "MS": ("own", "unverified", ""), "AR": ("own, IRC by reference item by item", "unverified", ""),
    "AL": ("own AGI (largely federal items)", "unverified", ""),
}
FEDTAX = {"AL": "yes, full federal liability", "MO": "yes, 35%..0% of federal tax by MO AGI, cap $5,000/$10,000",
          "OR": "yes, capped and phased out by AGI", "LA": "repealed from 2022", "MT": "repealed from 2024", "IA": "repealed (unverified year)"}
TIED = {"DC": "tied (PE run)", "GA": "tied (PE run)"}
rows = []
states = sorted(probe)
for st in states:
    p = probe[st]
    b = p["base"]
    d = lambda v: p[v]["state"] - b["state"]
    dh = p["ot_hi"]["state"] - p["base_hi"]["state"]
    if st in NO_TAX:
        rows.append(dict(state=st, wage_income_tax=False, note="no tax on wages for 2025"))
        continue
    s1a = {"tips": d("tips"), "overtime": d("ot") if b["state"] else dh, "car_interest": d("auto")}
    inherits = "yes" if s1a["tips"] < 0 and s1a["overtime"] < 0 and s1a["car_interest"] < 0 else "yes (overtime at $120k; $60k is in the zero bracket)" if b["state"] == 0 and s1a["overtime"] < 0 else (
        "no (state tax rises: smaller federal-tax deduction)" if s1a["tips"] > 0 else "no")
    sp = START.get(st, ("federal AGI", "unverified", ""))
    e = cm.get(st.lower(), {})
    rows.append(dict(state=st, wage_income_tax=True, start=sp[0], start_confidence=sp[1], start_source=sp[2],
                     sch1a_pe=inherits, sch1a_state_tax_change_pe=s1a, hsa_pe=("yes" if d("hsa") < 0 else "no"),
                     k401_pe=("yes" if d("k401") < 0 else "no"),
                     fedtax_ded=FEDTAX.get(st, "no"),
                     eitc_pct_pe=[x["value_2025"] for x in e.get("eitc", [])],
                     cdcc_pct_pe=[x["value_2025"] for x in e.get("cdcc", [])],
                     itemize_tie=TIED.get(st, "not checked"),
                     conformity_type="not verified"))
json.dump(rows, open("conformity.json", "w"), indent=1)
md = ["# State conformity, tax year 2025 (50 states + DC)", "",
      "Generated by `conformity.py`. 'PE' columns are PolicyEngine-US 2.138.1 behaviour (single filer, $60,000 wages; "
      "overtime also at $120,000), not checked law. Starting points are 'unverified' unless a source is given. "
      "Conformity type (rolling/static/selective) was not verified for any state except Iowa and is left blank.", "",
      "| State | Start | Conf. | Sch. 1-A flows (PE) | HSA (PE) | Fed. tax deduction | EITC % fed (PE) | CDCC % fed (PE) | Itemize tie |",
      "|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    if not r["wage_income_tax"]:
        md.append(f"| {r['state']} | no tax on wages | | | | | | | |")
        continue
    md.append(f"| {r['state']} | {r['start']} | {r['start_confidence']} | {r['sch1a_pe']} | {r['hsa_pe']} | {r['fedtax_ded']} | "
              f"{','.join(str(x) for x in r['eitc_pct_pe'] if x is not None) or '-'} | {','.join(str(x) for x in r['cdcc_pct_pe'] if x is not None) or '-'} | {r['itemize_tie']} |")
open("conformity.md", "w").write("\n".join(md) + "\n")
print("\n".join(md))
