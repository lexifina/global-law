"""Every printed cell of Tableaux 6 and 7 (both editions) against the first taxable income Lean's tableTax gives.
Writes lean/FrTax/Brochure67.lean: one kernel-checked theorem per printed cell (right or wrong)."""
import os, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
from thresholds import parse

LEAN = os.path.expanduser("~/fr/lean/.lake/build/bin/frtax")


def tax(year, sit, q, rs):
    inp = "".join(f"T;{r};{year};{sit};{q};{r}\n" for r in rs)
    out = subprocess.run([LEAN], input=inp, capture_output=True, text=True).stdout
    return {int(l.split(";")[0]): int(float(l.split("=")[1])) for l in out.splitlines()}


def first(year, sit, q, thr):
    lo, hi = 0, 200000
    while lo < hi:
        mid = (lo + hi) // 2
        if tax(year, sit, q, [mid])[mid] >= thr:
            hi = mid
        else:
            lo = mid + 1
    return lo


thms, rows = [], []
for ed, year, p in (("2025", 2024, "p2024"), ("2026", 2025, "p2025")):
    _, t67 = parse(ed)
    for tab, thr in (("Tableau 6", 1), ("Tableau 7", 61)):
        for row, sit in (("seule", 0), ("couple", 4)):
            for parts, printed in sorted(t67[tab][row].items()):
                q = int(round(parts * 4))
                f = first(year, sit, q, thr)
                t = tax(year, sit, q, [f - 1, f])
                ok = f == printed
                rows.append((ed, tab, row, parts, printed, f, ok))
                name = f"b{ed}_t{tab[-1]}_{row}_{str(parts).replace('.', '_')}"
                stmt = (f"tableTax {p} {sit} {q} {f} ≥ {thr} ∧ tableTax {p} {sit} {q} {f - 1} < {thr}")
                doc = (f"Edition {ed}, {tab}, {row}, {parts} parts: printed {printed} €; the first taxable income with a tax of "
                       f"{thr} € or more is {f} €" + ("" if ok else " (the printed figure is wrong)") + ".")
                thms.append(f"/-- {doc} -/\ntheorem {name} : {stmt} := by decide\n")
lean = ("import FrTax.Tax\n\n/-! Every cell of Tableaux 6 and 7 of the brochure pratique (editions 2025 and 2026), generated by\n"
        "harness/t67_all.py: the first taxable income at which the tax (after the cap and the décote) reaches 1 € (Tableau 6)\n"
        "or 61 € (Tableau 7). -/\n\nnamespace FrTax\n\n" + "\n".join(thms) + "\nend FrTax\n")
open(os.path.expanduser("~/fr/lean/FrTax/Brochure67.lean"), "w").write(lean)
for r in rows:
    print(*r)
print("cells", len(rows), "right", sum(r[6] for r in rows), "wrong", sum(not r[6] for r in rows))
