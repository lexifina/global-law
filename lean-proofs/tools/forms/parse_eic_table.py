"""Parse the 2025 EIC Table (Publication 1040 (2025), i1040tt.pdf, pdftotext -layout) into Lean data.
Rows: (at least, but less than, [single/HOH/QSS 0,1,2,3 children, MFJ 0,1,2,3]); a starred cell is -1 and its
footnote ("at least $X but less than $Y ... your credit is $Z"; $Y or more: no credit) becomes a `split` entry.
Usage: python3 -I parse_eic_table.py ~/docs/irs/i1040tt.txt out.lean"""
import re, sys
txt = open(sys.argv[1], encoding='utf-8').read()
start = txt.index('2025 Earned Income Credit (EIC)')
body = txt[start:]
cell = r'(\d{1,3}(?:,\d{3})*|\*+)'
num = r'(\d{1,3}(?:,\d{3})*)'
row = re.compile(r'\s+'.join([num, num] + [cell] * 8))
rows = {}
for line in body.splitlines():
    for m in row.finditer(line):
        g = m.groups()
        lo, hi = int(g[0].replace(',', '')), int(g[1].replace(',', ''))
        if hi - lo not in (49, 50):
            continue
        vs = [-1 if c.startswith('*') else int(c.replace(',', '')) for c in g[2:]]
        if lo in rows and rows[lo] != (hi, vs):
            raise SystemExit('conflict at %d' % lo)
        rows[lo] = (hi, vs)
rows = sorted((lo, hi, vs) for lo, (hi, vs) in rows.items())
assert rows[0][0] == 1 and rows[0][1] == 50, rows[0]
for a, b in zip(rows, rows[1:]):
    assert a[1] == b[0], (a[:2], b[:2])
flat = ' '.join(body.split())
notes = re.findall(r'at least \$([\d,]+) but less than \$([\d,]+), and you have (no|one|two|three) qualifying child\w* '
                   r'who ha\w+ (?:a )?valid SSNs?, your credit is \$(\d+)', flat)
kids = {'no': 0, 'one': 1, 'two': 2, 'three': 3}
splits = []
for lo, co, k, v in notes:
    lo, co, v = int(lo.replace(',', '')), int(co.replace(',', '')), int(v)
    r = next(r for r in rows if r[0] == lo)
    cols = [c for c in range(8) if r[2][c] == -1 and c % 4 == kids[k]]
    assert len(cols) == 1, (lo, k, r)
    splits.append((cols[0], lo, co, v))
stars = sum(v == -1 for r in rows for v in r[2])
assert stars == len(splits), (stars, splits)
print(len(rows), 'rows', len(splits), 'starred cells', splits, rows[-1][:2], file=sys.stderr)
ty = 'List (Int × Int × List Int)'
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('/-! Generated by tools/forms/parse_eic_table.py from the 2025 EIC Table (Publication 1040 (2025), '
            'irs.gov/pub/irs-pdf/i1040tt.pdf, pdftotext -layout). Rows: (at least, but less than, [single/HOH/QSS '
            'with 0, 1, 2, 3 children; MFJ with 0, 1, 2, 3 children]); -1 marks a starred cell, resolved by '
            '`splits` = (column, at least, less than, credit) from the footnotes; at or above the footnote\'s '
            '"less than" amount the credit is 0. Do not edit. -/\n\nnamespace TaxCode.Forms.EIC\n\n')
    chunks = [rows[k:k + 100] for k in range(0, len(rows), 100)]
    for n, ch in enumerate(chunks):
        f.write('def rows%d : %s := [\n' % (n, ty))
        f.write(',\n'.join('  (%d, %d, [%s])' % (lo, hi, ', '.join(map(str, vs))) for lo, hi, vs in ch))
        f.write(']\n\n')
    f.write('def rows : %s :=\n  %s\n\n' % (ty, ' ++ '.join('rows%d' % n for n in range(len(chunks)))))
    f.write('def splits : List (Nat × Int × Int × Int) := [%s]\n\nend TaxCode.Forms.EIC\n'
            % ', '.join('(%d, %d, %d, %d)' % s for s in splits))
