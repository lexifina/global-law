"""Parse the 2025 Tax Table (Publication 1040 Tax Table, i1040tt.pdf, pdftotext -layout) into rows
(at_least, less_than, single, mfj, mfs, hoh) and write a Lean data module. Usage:
  python3 -I parse_tax_table.py ~/docs/irs/i1040tt.txt out.lean"""
import re, sys
txt = open(sys.argv[1], encoding='utf-8').read()
end = txt.index('2025 Tax Computation Worksheet—Line 16')
body = txt[:end]
num = r'(\d{1,3}(?:,\d{3})*)'
row = re.compile(r'\s'.join([num]*6) .replace(r'\s', r'\s+'))
rows = set()
for line in body.splitlines():
    for m in row.finditer(line):
        v = [int(g.replace(',', '')) for g in m.groups()]
        if v[1] > v[0]:
            rows.add(tuple(v))
# The first three lines (0-5, 5-15, 15-25) are printed with the numbers stacked vertically, which pdftotext breaks
# apart (page 2: "5 / 5 15 / 0 1 / 0 1 / 0 1 / 0 1", then "15 25 2 2 2 2"); they are read by hand from that text.
rows.add((15, 25, 2, 2, 2, 2))
rows |= {(0, 5, 0, 0, 0, 0), (5, 15, 1, 1, 1, 1)}
rows = sorted(rows)
# contiguity check
assert rows[0][0] == 0, rows[0]
for a, b in zip(rows, rows[1:]):
    assert a[1] == b[0], (a, b)
assert rows[-1][1] == 100000, rows[-1]
print(len(rows), 'rows', rows[:5], rows[-2:], file=sys.stderr)
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('/-! Generated by tools/forms/parse_tax_table.py from the 2025 Tax Table (Publication 1040 (2025), '
            'irs.gov/pub/irs-pdf/i1040tt.pdf, pdftotext -layout). Rows: (at least, but less than, single, '
            'married filing jointly, married filing separately, head of household). Do not edit. -/\n\n')
    f.write('namespace TaxCode.Forms.TaxTable\n\n')
    ty = 'List (Int × Int × Int × Int × Int × Int)'
    chunks = [rows[k:k + 100] for k in range(0, len(rows), 100)]
    for n, ch in enumerate(chunks):
        f.write('def rows%d : %s := [\n' % (n, ty))
        f.write(',\n'.join('  (%d, %d, %d, %d, %d, %d)' % r for r in ch))
        f.write(']\n\n')
    f.write('def rows : %s :=\n  %s\n\nend TaxCode.Forms.TaxTable\n'
            % (ty, ' ++ '.join('rows%d' % n for n in range(len(chunks)))))
