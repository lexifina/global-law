"""Turn every cliff the Lean search found into a Lean theorem the kernel re-checks.

    lake env lean LegalProofs/USTax/Search.lean   # writes tools/out/tax_*.json
    python tools/gen_tax_certs.py                 # -> LegalProofs/USTax/Generated/*.lean
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "LegalProofs" / "USTax" / "Generated"
CHUNK = 100
ST = {"single": ".single", "mfj": ".mfj", "hoh": ".hoh"}


def main():
    inv = json.loads((ROOT / "tools/out/tax_interest_cliff.json").read_text())
    wage = [c for c in json.loads((ROOT / "tools/out/tax_wage_cliffs.json").read_text()) if c["drop"] >= 10]
    cases = []
    for c in inv:   # interest 11,950 -> 11,951
        cases.append((f"⟨{ST[c['status']]}, {c['kids']}, {c['wages']}, 11950, 0⟩", f"⟨{ST[c['status']]}, {c['kids']}, {c['wages']}, 11951, 0⟩", c["drop"]))
    for c in wage:  # wages w -> w + 1
        cases.append((f"⟨{ST[c['status']]}, {c['kids']}, {c['wages']}, 0, {c['ira']}⟩", f"⟨{ST[c['status']]}, {c['kids']}, {c['wages'] + 1}, 0, {c['ira']}⟩", c["drop"]))
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*.lean"):
        f.unlink()
    names = []
    for k in range(0, len(cases), CHUNK):
        part = cases[k:k + CHUNK]; name = f"Cliffs{k // CHUNK:03d}"; names.append(name)
        body = ",\n  ".join(f"({a}, {b}, {d})" for a, b, d in part)
        (OUT / f"{name}.lean").write_text(
            "import LegalProofs.USTax.Model\n\nset_option maxRecDepth 20000\n\n-- Generated by tools/gen_tax_certs.py from the Lean search. Do not edit.\n"
            f"namespace Legal.USTax.Generated.{name}\nopen Legal.USTax\n\n"
            f"/-- (before, after, drop): one more dollar takes the household from `before` to `after` and costs `drop`. -/\n"
            f"def cliffs : List (Household × Household × Nat) := [\n  {body}]\n\n"
            "/-- Every listed dollar really costs the stated amount. -/\n"
            "theorem all_hold : cliffs.all (fun (a, b, d) => net b + d == net a) = true := by decide\n\n"
            f"end Legal.USTax.Generated.{name}\n", encoding="utf-8", newline="\n")
    (ROOT / "LegalProofs" / "USTax" / "Generated.lean").write_text(
        "".join(f"import LegalProofs.USTax.Generated.{n}\n" for n in names), encoding="utf-8", newline="\n")
    print(len(cases), "cliffs in", len(names), "files")


if __name__ == "__main__":
    main()
