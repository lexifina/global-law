"""Generate Lean certificates for empty periods, pre-publication dates and missing paragraphs.

Reads only ../vulnerabilities/data/flags.parquet (the facts are in each flag's summary and reference) and writes
LegalProofs/Generated/{Gap,Prepub,Para}NNN.lean plus tools/out/certificates_more.json.

    python tools/gen_more.py
"""
from __future__ import annotations
import collections, datetime as dt, json, re
from pathlib import Path
import duckdb

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
FLAGS = ROOT.parent / "vulnerabilities" / "data" / "flags.parquet"
GEN = ROOT / "LegalProofs" / "Generated"
CHUNK = 100
GAP = re.compile(r"ran until (\d{4}-\d{2}-\d{2}); extended to (\d{4}-\d{2}-\d{2}) by an amendment in force (\d{4}-\d{2}-\d{2})")
PRE = re.compile(r"dated in force (\d+) days before it was (\w+)")
PARA = re.compile(r"(?:Abs\.|Absatz) (\d+) → \S+ \(has ([\w,]+)\)")


def n(d: dt.date) -> int:
    return d.year * 10000 + d.month * 100 + d.day


def main() -> None:
    rows = duckdb.sql(f"""select id, category, corpus, path, date, reference, summary from '{FLAGS.as_posix()}'
        where category in ('Empty periods', 'Retroactive or pre-publication dates', 'Missing paragraphs (Germany)')""").fetchall()
    gaps, pres, paras, skipped = [], [], [], collections.Counter()
    for fid, cat, corpus, path, date, ref, summ in rows:
        base = {"id": fid, "category": cat, "corpus": corpus, "path": path}
        if cat == "Empty periods":
            m = GAP.search(summ or "")
            if not m:
                skipped[cat] += 1; continue
            until, new, eff = (dt.date.fromisoformat(x) for x in m.groups())
            w = until + dt.timedelta(days=1)
            gaps.append({**base, "endsOn": n(until), "newUntil": n(new), "extendedFrom": n(eff), "witness": n(w),
                         "certified": w < eff})
        elif cat == "Retroactive or pre-publication dates":
            m = PRE.search(summ or "")
            if not m or not date:
                skipped[cat] += 1; continue
            stated = dt.date.fromisoformat(date[:10])
            made = stated + dt.timedelta(days=int(m.group(1)))
            pres.append({**base, "statedFrom": n(stated), "madeOn": n(made), "against": m.group(2), "certified": stated < made})
        else:
            m = PARA.search(ref or "")
            has = m.group(2).split(",") if m else []
            if not m or not all(h.isdigit() for h in has):
                skipped[cat] += 1; continue
            p = int(m.group(1)); hs = [int(h) for h in has]
            paras.append({**base, "para": p, "has": hs, "certified": p not in hs})

    for old in list(GEN.glob("Gap*.lean")) + list(GEN.glob("Prepub*.lean")) + list(GEN.glob("Para*.lean")):
        old.unlink()
    names = []
    bools = lambda xs: "[" + ", ".join("true" if x else "false" for x in xs) + "]"
    specs = [
        ("Gap", "GapFlag", gaps, lambda r: f"⟨⟨{r['endsOn']}, {r['extendedFrom']}, {r['newUntil']}⟩, {r['witness']}⟩"),
        ("Prepub", "PrepubFlag", pres, lambda r: f"⟨{r['statedFrom']}, {r['madeOn']}⟩"),
        ("Para", "ParaFlag", paras, lambda r: f"⟨{r['para']}, [{', '.join(map(str, r['has']))}]⟩"),
    ]
    for prefix, ty, recs, lit in specs:
        for k in range(0, len(recs), CHUNK):
            part = recs[k:k + CHUNK]; name = f"{prefix}{k // CHUNK:03d}"; names.append(name)
            (GEN / f"{name}.lean").write_text(
                "import LegalProofs.Certificates\n\n-- Generated by tools/gen_more.py from the published flag list. Do not edit.\n"
                f"namespace Legal.Generated.{name}\n\n"
                f"def flags : List {ty} := [\n  " + ",\n  ".join(lit(r) for r in part) + "]\n\n"
                "/-- Lean evaluates every certificate; the right-hand side is the generator's verdict. -/\n"
                f"theorem certified : flags.map (·.certified) = {bools([r['certified'] for r in part])} := by decide\n\n"
                f"end Legal.Generated.{name}\n", encoding="utf-8", newline="\n")
    (ROOT / "LegalProofs" / "GeneratedMore.lean").write_text(
        "-- Generated by tools/gen_more.py.\n" + "".join(f"import LegalProofs.Generated.{x}\n" for x in names), encoding="utf-8", newline="\n")
    (HERE / "out").mkdir(exist_ok=True)
    (HERE / "out" / "certificates_more.json").write_text(json.dumps({"gaps": gaps, "prepub": pres, "paras": paras,
                                                                      "skipped": dict(skipped)}, ensure_ascii=False), encoding="utf-8")
    for label, recs in (("empty periods", gaps), ("pre-publication", pres), ("missing paragraphs", paras)):
        print(f"{label}: {len(recs)} parsed, {sum(r['certified'] for r in recs)} certified")
    print("skipped (facts not in the flag text):", dict(skipped))


if __name__ == "__main__":
    main()
