#!/usr/bin/env python3
"""Turn the BMF interface answers (runs/bmf_pap/<id>.xml) into Lean #guard checks (lean/DeTax/PapBmf.lean)."""
import json, os, re, sys, datetime
cases = [json.loads(l) for l in open('runs/pap_all.jsonl')]
rows = []
for c in cases:
    p = f"runs/bmf_pap/{c['id']}.xml"
    if not os.path.exists(p): continue
    s = open(p, encoding='utf-8', errors='replace').read()
    out = {m.group(1): int(m.group(2)) for m in re.finditer(r'<ausgabe name="(\w+)" value="(-?\d+)"', s)}
    if not all(k in out for k in ['LSTLZZ', 'SOLZLZZ', 'BK', 'VFRB', 'WVFRB']): continue
    zkf10 = round(c['ZKF'] * 10); kvz = round(c['KVZ'] * 100)
    inp = (f"{{ LZZ := {c['LZZ']}, RE4 := {c['RE4']}, STKL := {c['STKL']}, ZKF10 := {zkf10}, KRV := {c['KRV']}, "
           f"KVZbp := {kvz}, PKV := {c['PKV']}, PKPV := {c['PKPV']}, PVS := {c['PVS']}, PVZ := {c['PVZ']}, "
           f"PVA := {c['PVA']}, R := {c['R']}, ALTER1 := {c['ALTER1']}, AJAHR := {c['AJAHR']}, "
           f"LZZFREIB := {c['LZZFREIB']}, LZZHINZU := {c['LZZHINZU']} }}")
    rows.append(f"  ({inp}, {out['LSTLZZ']}, {out['SOLZLZZ']}, {out['BK']}, {out['VFRB']}, {out['WVFRB']})")
hdr = f'''import DeTax.Pap

/-!
# The BMF's own calculator, as test cases

Each row is one request to the BMF's external interface for the PAP 2025
(`https://www.bmf-steuerrechner.de/interface/2025Version1.xhtml`, the interface the BMF provides "für die
automatisierte, maschinelle Prüfung eines Lohn- und Einkommensteuerrechners gegen den des BMF"; requests 61 s apart)
and the five outputs it returned (LSTLZZ, SOLZLZZ, BK, VFRB, WVFRB, in cents). Inputs: `runs/pap_all.jsonl` (44 cases
at the tariff and Soli boundaries, then random cases over pay periods, Steuerklassen, children, KRV, Zusatzbeitrag,
private insurance, Saxony, PV surcharge and reductions, church, Altersentlastungsbetrag, Freibetrag/Hinzurechnung).
Generated by `harness/gen_papbmf.py` on {datetime.date.today()}: {len(rows)} answers.
-/

namespace DeTax.PapBmf
open DeTax

def answers : List (Pap.In × Int × Int × Int × Int × Int) := [
'''
body = ",\n".join(rows)
ftr = '''
]

-- The Lean PAP reproduces every answer of the BMF calculator.
#guard answers.all fun (i, l, s, b, v, w) =>
  let o := Pap.run i
  o.LSTLZZ == l && o.SOLZLZZ == s && o.BK == b && o.VFRB == v && o.WVFRB == w

#eval answers.length

end DeTax.PapBmf
'''
open('lean/DeTax/PapBmf.lean', 'w').write(hdr + body + ftr)
print(len(rows))
