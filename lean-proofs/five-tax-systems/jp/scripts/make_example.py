"""Regenerate ~/cmp/jp/EXAMPLE.md from the sample households and the current jptax build.
usage: python3 -I make_example.py"""
import json, os, subprocess

HOME = os.path.expanduser("~/cmp/jp")
EXE = HOME + "/lean/.lake/build/bin/jptax"
samples = [
    {"id": "jp-ex1", "year": 2025,
     "adults": [{"age": 45, "wages": 8000000, "selfEmployment": 0, "pension": 0},
                {"age": 43, "wages": 1000000, "selfEmployment": 0, "pension": 0}],
     "married": True, "children": [{"age": 17}, {"age": 10}, {"age": 2}],
     "interest": 10000, "dividends": 100000, "capitalGains": 50000, "rentalIncome": 0, "charitable": 30000,
     "pensionContributions": 100000},
    {"id": "jp-ex2-single-AW", "year": 2025,
     "adults": [{"age": 30, "wages": 5703038, "selfEmployment": 0, "pension": 0}],
     "married": False, "children": [], "interest": 0, "dividends": 0, "capitalGains": 0, "rentalIncome": 0,
     "charitable": 0, "pensionContributions": 0},
]
inp = "\n".join(json.dumps(h, ensure_ascii=False) for h in samples) + "\n"
out = subprocess.run([EXE], input=inp.encode(), capture_output=True, check=True).stdout.decode().strip().splitlines()

doc = []
doc.append("# jptax — example input and output (for the comparison harness)\n")
doc.append("Binary: `~/cmp/jp/lean/.lake/build/bin/jptax` (build: `cd ~/cmp/jp/lean && lake build`).")
doc.append("Usage: `jptax households.jsonl > out.jsonl` or `cat households.jsonl | jptax`. One output line per input line, same")
doc.append("order; about 80 µs per household. Regenerated by `scripts/make_example.py` from the current build.\n")
doc.append("## Input (contract format)\n\n```json")
doc.extend(json.dumps(h, ensure_ascii=False) for h in samples)
doc.append("```\n\n## Output\n\n```json")
doc.extend(out)
doc.append("```\n")
s1 = json.loads(out[0])
doc.append("Reading the first output: 所得税 %s yen (both adults' 基準所得税額 + 15 %% on the investment income), 復興特別所得税 %s,"
           % (format(s1["incomeTax"], ","), format(s1["surtaxes"]["復興特別所得税"], ",")))
doc.append("住民税 %s (令和8年度 tax on 2025 income), employee contributions %s, 児童手当 %s (one child under 3 as the third"
           % (format(s1["localIncomeTax"], ","), format(s1["employeeSocial"], ","), format(s1["benefits"], ",")))
doc.append("child: 30,000 a month, two aged 3–18: 10,000 each). The second adult (1,000,000 yen) is below the 88,000-yen monthly")
doc.append("threshold, so is a 被扶養者 and pays no contributions; the first adult claims the second (配偶者控除 380,000) and the children.\n")
doc.append("""## How the fields map

* `incomeTax` = 所得税: each adult's 基準所得税額 (所得税法, after 配当控除), any 措置法第41条の19 minimum tax, and the 15 %
  national part of the separate taxes on interest, dividends and listed-share gains.
* `surtaxes.復興特別所得税` = 2.1 % of each adult's 基準所得税額 (cut to the yen) + 0.315 % on the separately taxed investment
  income. The amount actually paid (所得税 + 復興 cut to 100 yen) is `detail.persons[].nationalPayableRounded100`.
* `localIncomeTax` = 個人住民税 for 令和8年度 computed on 2025 income (paid June 2026 – May 2027), Tokyo 23 wards, standard
  rates: 所得割 (都 4 % + 区 6 %, after 調整控除, each cut to 100 yen) + 均等割 (1,000 + 3,000) + 森林環境税 (1,000, a national
  tax collected with the 均等割) + 利子割 / 配当割 / 株式等譲渡所得割 (5 %).
* `employeeSocial` = employee shares for calendar 2025: 協会けんぽ 東京 health (9.98 % → 9.91 % from March) + 介護 for ages
  40–64 (1.60 % → 1.59 %), 厚生年金 18.3 %, 雇用保険 (6/1000 → 5.5/1000 from April); 標準報酬月額 grades and caps; 12 equal
  monthly payments, no bonus. Insured from a monthly wage of 88,000 yen (large employer); a spouse below that with income
  under 1,300,000 yen is a 被扶養者 and pays nothing.
* `benefits` = 児童手当 for 12 months (15,000 yen under 3, 10,000 yen 3–18, 30,000 yen from the third child counting
  children up to 22; no income limit).

## Conventions

* Ages are on 31 December 2025. Children are claimed by the adult with the larger income; the higher-income spouse
  claims the other (配偶者控除 / 配偶者特別控除). One unmarried adult with a child is a ひとり親.
* Dividends: default 確定申告不要 (20.315 % withheld, final, outside 合計所得金額); `"jpDividends": "aggregate"` taxes
  them in the progressive scale with 配当控除. Interest: 源泉分離 20.315 %. Capital gains: 特定口座 with withholding
  20.315 %. Investment income, rental income and aggregate dividends are split equally between the adults.
* `selfEmployment` is net 事業所得 (白色申告: no 青色申告特別控除). `pensionContributions` = iDeCo (fully deductible,
  up to the legal contribution limits). `charitable` = 特定寄附金 (所得控除 under 第78条; no 住民税 credit).
* Japan-only optional input fields: `children[].wages` (a child's salary), `jpDividends` ("separate" default = 確定申告不要,
  "aggregate" = 総合課税 with 配当控除, "declared" = 申告分離課税), `jpGains` ("withheld" default, "declared"),
  `jpSingleParentSex` ("F"/"M").
* Not modelled: 国民年金 / 国民健康保険 of the self-employed and of non-insured earners (listed in `unsupported`),
  medical, life-insurance and earthquake deductions, 住宅ローン控除, ふるさと納税, disability and student deductions,
  児童扶養手当.
""")
open(HOME + "/EXAMPLE.md", "w", encoding="utf-8").write("\n".join(doc))
print("EXAMPLE.md written;", len(out), "outputs")
