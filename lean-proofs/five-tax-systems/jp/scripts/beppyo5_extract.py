"""Extract 所得税法 別表第五 (年末調整等のための給与所得控除後の給与等の金額の表) from the e-Gov XML into
(lo, hi, value) rows, check that they tile [1,900,000, 6,600,000) in 4,000-yen rows, and write a Lean data file.
usage: python3 -I beppyo5_extract.py <law xml> <out.lean>"""
import sys, re
import xml.etree.ElementTree as ET

FW = str.maketrans("０１２３４５６７８９，", "0123456789,")


def num(s):
    s = s.translate(FW).replace(",", "").replace("円", "").strip()
    return int(s) if re.fullmatch(r"\d+", s) else None


root = ET.parse(sys.argv[1]).getroot()
table = None
for t in root.iter("AppdxTable"):
    tt = t.find("AppdxTableTitle")
    if tt is not None and "別表第五" in "".join(tt.itertext()):
        table = t
assert table is not None
rows = []
for tr in table.iter("TableRow"):
    cells = ["".join(c.itertext()).strip() for c in tr.findall("TableColumn")]
    vals = [num(c) for c in cells]
    # scan for consecutive integer triples lo < hi, value
    i = 0
    while i + 2 < len(vals):
        a, b, c = vals[i], vals[i + 1], vals[i + 2]
        if a is not None and b is not None and c is not None and b - a == 4000 and 1900000 <= a < 6600000:
            rows.append((a, b, c))
            i += 3
        else:
            i += 1
rows = sorted(set(rows))
print("rows:", len(rows), "first", rows[0], "last", rows[-1])
assert rows[0][0] == 1900000 and rows[-1][1] == 6600000
for (a, b, c), (a2, b2, c2) in zip(rows, rows[1:]):
    assert b == a2, (a, b, a2)
assert len(rows) == (6600000 - 1900000) // 4000
with open(sys.argv[2], "w") as f:
    f.write("import JpTax.Income\n\n/-!\n# 所得税法 別表第五, the 4,000-yen rows (machine-extracted)\n\n")
    f.write("Rows of \"年末調整等のための給与所得控除後の給与等の金額の表\" from 1,900,000 to 6,600,000 yen, as published in\n")
    f.write("the e-Gov 法令API v2 XML of 所得税法 (revision 340AC0000000033_20251218_507AC0000000013, 令和7年法律第13号):\n")
    f.write("(給与等の金額 以上, 未満, 給与所得控除後の給与等の金額). Generated by `scripts/beppyo5_extract.py`; do not edit.\n-/\n\n")
    f.write("namespace JpTax\n\n")
    CH = 25
    chunks = [rows[i:i + CH] for i in range(0, len(rows), CH)]
    for ci, ch in enumerate(chunks):
        f.write("def beppyo5Chunk%d : List (Int × Int × Int) := [\n" % ci)
        f.write(",\n".join("  (%d, %d, %d)" % r for r in ch))
        f.write("]\n\n")
    f.write("/-- All rows, in order (%d chunks of up to %d rows). -/\n" % (len(chunks), CH))
    f.write("def beppyo5Chunks : List (List (Int × Int × Int)) := [\n  ")
    f.write(",\n  ".join("beppyo5Chunk%d" % i for i in range(len(chunks))))
    f.write("]\n\ndef beppyo5Rows : List (Int × Int × Int) := beppyo5Chunks.flatten\n\n")
    f.write("/-! Each chunk checked in the kernel against the closed form `kyuyoShotoku` at both ends of every row. -/\n\n")
    for ci in range(len(chunks)):
        f.write("theorem beppyo5Chunk%d_ok : beppyo5Chunk%d.all beppyo5RowOk = true := by decide\n" % (ci, ci))
    f.write("\ntheorem beppyo5Rows_ok : beppyo5Rows.all beppyo5RowOk = true := by\n")
    f.write("  simp only [beppyo5Rows, beppyo5Chunks, List.all_flatten, List.all_cons, List.all_nil, Bool.and_true,\n    ")
    f.write(", ".join("beppyo5Chunk%d_ok" % i for i in range(len(chunks))))
    f.write("]\n\nend JpTax\n")
print("written", sys.argv[2], "chunks", len(chunks))
