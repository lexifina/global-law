"""Statement lock and trust audit for caselaw-lean-2 (DESIGN D2).

    python audit.py check                     # verify; exit 1 on any problem
    python audit.py lock --reason "..."       # accept the current statements (logs every change to STATEMENTS.log)

What it does:
1. Lists every theorem declared in a LegalProofs.CaseLaw2.* module (ListTheorems.lean, from the Lean environment).
2. Elaborates `#check @thm` and `#print axioms thm` for each, with `lean --json`.
3. check: every theorem's statement equals the locked one (statements.lock), no theorem is missing or new, every
   theorem's axioms are within {propext, Classical.choice, Quot.sound}, and no CaseLaw2 source contains `sorry`,
   `admit`, `native_decide` or an `axiom` declaration.
4. lock: rewrites statements.lock, LegalProofs/CaseLaw2/Registry.lean (the registry) and
   LegalProofs/CaseLaw2/Audit.lean (`#guard_msgs` on every statement and axiom list, so `lake build` itself fails if a
   locked statement changes). A statement change needs --reason; it is logged, never silent. Policy: a weakened
   statement is escalated as a probable spec/data bug; a false property is refuted (counterexample kept as a #guard),
   never weakened.
"""
import datetime
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.dirname(HERE)
LP = os.environ.get("CASELAW2_LP") or os.path.dirname(WORK)  # lean-proofs/ (this file: lean-proofs/caselaw2/audit/)
SRC = os.path.join(LP, "LegalProofs", "CaseLaw2")
LOCK = os.path.join(HERE, "statements.lock")
LOG = os.path.join(WORK, "STATEMENTS.log")
ALLOWED = {"propext", "Classical.choice", "Quot.sound"}
ENV = dict(os.environ, PATH=os.path.expanduser("~/.elan/bin") + os.pathsep + os.environ.get("PATH", ""))


def lean_json(path):
    r = subprocess.run(["lake", "env", "lean", "--json", path], cwd=LP, env=ENV, capture_output=True, text=True,
                       encoding="utf-8")
    msgs = []
    for line in r.stdout.splitlines():
        line = line.strip()
        if line.startswith("{"):
            try:
                msgs.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return msgs, r


def list_theorems():
    msgs, r = lean_json(os.path.join(HERE, "ListTheorems.lean"))
    out = []
    for m in msgs:
        for line in m.get("data", "").splitlines():
            if line.startswith("THM\t"):
                _, name, mod, doc = (line.split("\t") + [""])[:4]
                out.append((name, mod, doc.strip()))
    if not out:
        sys.exit("lister produced nothing:\n" + r.stdout[-2000:] + r.stderr[-2000:])
    return sorted(set(out))


def elaborate(names):
    tmp = os.path.join(HERE, "_elab.lean")
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("import LegalProofs.CaseLaw2.Core\n")
        for n in names:
            f.write(f"#check @{n}\n#print axioms {n}\n")
    msgs, r = lean_json(tmp)
    os.remove(tmp)
    # messages arrive in source order: line 2k+2 = #check of names[k], 2k+3 = axioms
    by_line = {}
    for m in msgs:
        by_line.setdefault(m["pos"]["line"], []).append(m)
    res = {}
    for k, n in enumerate(names):
        chk = by_line.get(2 * k + 2, [])
        ax = by_line.get(2 * k + 3, [])
        stmt = "\n".join(m["data"] for m in chk).strip()
        axs = "\n".join(m["data"] for m in ax).strip()
        sev = [m["severity"] for m in chk + ax]
        res[n] = (stmt, axs, "error" in sev)
    return res


def axioms_of(text):
    m = re.search(r"depends on axioms: \[(.*)\]", text, re.S)
    if not m:
        return set()
    return {a.strip() for a in m.group(1).replace("\n", " ").split(",") if a.strip()}


def source_hygiene():
    bad = []
    for root, _, files in os.walk(SRC):
        for fn in files:
            if not fn.endswith(".lean") or fn == "Audit.lean":
                continue
            p = os.path.join(root, fn)
            code = open(p, encoding="utf-8").read()
            code = re.sub(r"/-.*?-/", "", code, flags=re.S)        # block comments / docstrings
            code = re.sub(r"--[^\n]*", "", code)
            for pat in [r"\bsorry\b", r"\badmit\b", r"\bnative_decide\b", r"^\s*axiom\b"]:
                if re.search(pat, code, re.M):
                    bad.append(f"{os.path.relpath(p, LP)}: {pat}")
    return bad


def read_lock():
    if not os.path.exists(LOCK):
        return {}
    data = json.load(open(LOCK, encoding="utf-8"))
    return {d["name"]: d for d in data}


def lean_string(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_lean(thms, elab):
    reg = os.path.join(SRC, "Registry.lean")
    with open(reg, "w", encoding="utf-8", newline="\n") as f:
        f.write("/-!\n# Theorem registry (generated by caselaw-lean-2/audit/audit.py; do not edit)\n\n"
                "Every theorem of caselaw-lean-2, with its module and the first sentence of its doc string. Each "
                "statement is locked in `statements.lock` and re-checked on every build by `Audit.lean`; changes go "
                "through `audit.py lock --reason` and are logged in `STATEMENTS.log`.\n-/\n\n"
                "namespace CaseLaw2.Registry\n\n/-- (theorem, module, description) -/\n"
                "def registry : List (String × String × String) := [\n")
        rows = []
        for n, mod, doc in thms:
            d = doc.split(". ")[0][:200]
            rows.append(f'  ("{n}", "{mod}", "{lean_string(d)}")')
        f.write(",\n".join(rows) + "\n]\n\n")
        f.write(f"#guard registry.length == {len(thms)}\n\nend CaseLaw2.Registry\n")
    aud = os.path.join(SRC, "Audit.lean")
    with open(aud, "w", encoding="utf-8", newline="\n") as f:
        f.write("import LegalProofs.CaseLaw2.Core\nimport LegalProofs.CaseLaw2.Registry\n\n"
                "/-!\n# Statement lock (generated by caselaw-lean-2/audit/audit.py; do not edit)\n\n"
                "For every registered theorem: its exact statement and its axioms. If a statement or its axioms "
                "change, this file stops building. Allowed axioms: propext, Classical.choice, Quot.sound.\n-/\n\n")
        for n, _, _ in thms:
            stmt, axs, _ = elab[n]
            for msg, cmd in [(stmt, f"#check @{n}"), (axs, f"#print axioms {n}")]:
                safe = msg.replace("-/", "- /")
                f.write(f"/-- info: {safe} -/\n#guard_msgs (whitespace := lax) in\n{cmd}\n\n")


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    reason = ""
    if "--reason" in sys.argv:
        reason = sys.argv[sys.argv.index("--reason") + 1]
    thms = list_theorems()
    names = [n for n, _, _ in thms]
    elab = elaborate(names)
    lock = read_lock()
    problems = []
    changes = []
    for n in names:
        stmt, axs, err = elab[n]
        if err:
            problems.append(f"{n}: elaboration error")
        extra = axioms_of(axs) - ALLOWED
        if extra:
            problems.append(f"{n}: axioms outside the allowed set: {sorted(extra)}")
        if n not in lock:
            changes.append(("new", n, "", stmt))
        elif lock[n]["statement"] != stmt:
            changes.append(("changed", n, lock[n]["statement"], stmt))
    for n in lock:
        if n not in names:
            changes.append(("removed", n, lock[n]["statement"], ""))
    problems += source_hygiene()
    axiom_free = sum(1 for n in names if not axioms_of(elab[n][1]))
    print(f"{len(names)} theorems; {axiom_free} use no axioms; {len(changes)} statement changes; "
          f"{len(problems)} problems")
    for c in changes:
        print(f"  {c[0]}: {c[1]}")
    for p in problems:
        print(f"  PROBLEM {p}")
    if mode == "lock":
        if problems:
            sys.exit("not locking while problems remain")
        if changes and lock and not reason:
            sys.exit("statement changes need --reason (they are logged in STATEMENTS.log)")
        if changes:
            with open(LOG, "a", encoding="utf-8", newline="\n") as f:
                f.write(f"\n## {datetime.datetime.now().isoformat(timespec='seconds')}  {reason or 'initial lock'}\n")
                for kind, n, old, new in changes:
                    f.write(f"- {kind}: {n}\n")
                    if kind == "changed":
                        f.write(f"  - was: {old}\n  - now: {new}\n")
        json.dump([{"name": n, "module": m, "doc": d, "statement": elab[n][0], "axioms": sorted(axioms_of(elab[n][1]))}
                   for n, m, d in thms], open(LOCK, "w", encoding="utf-8", newline="\n"), indent=1, ensure_ascii=False)
        write_lean(thms, elab)
        print("locked:", LOCK)
        return 0
    return 1 if (problems or changes) else 0


if __name__ == "__main__":
    sys.exit(main())
